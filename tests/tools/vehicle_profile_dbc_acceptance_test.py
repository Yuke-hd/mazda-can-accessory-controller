def sha(data):
    return hashlib.sha256(data).hexdigest()


class Workspace:
    """A temporary profile directory plus an output root; runs the CLI."""

    def __init__(self, test, sources, bindings, selected_bus="body", buses=None,
                 profile_id="synthetic.demo", name="profile"):
        temp = tempfile.TemporaryDirectory()
        test.addCleanup(temp.cleanup)
        self.root = Path(temp.name)
        self.inputs = self.root / name
        self.inputs.mkdir()
        self.out = self.root / "out"
        self.sources = dict(sources)
        self.buses = buses or {}
        self.document = {"version": 1, "profile_id": profile_id, "selected_bus": selected_bus,
                         "sources": [], "bindings": json.loads(json.dumps(bindings))}
        self.write(order=list(self.sources))

    def write(self, order=None, **license_overrides):
        order = order or [s["path"] for s in self.document["sources"]]
        for filename, data in self.sources.items():
            (self.inputs / filename).write_bytes(data)
        self.document["sources"] = [
            {"path": filename, "sha256": sha(self.sources[filename]),
             "bus": self.buses.get(filename, self.document["selected_bus"]),
             "license": license_overrides.get(filename, "Apache-2.0; synthetic fixture")}
            for filename in order]
        self.mapping.write_text(json.dumps(self.document, indent=1))

    @property
    def mapping(self):
        return self.inputs / "mapping.json"

    def run(self, *extra, out=None):
        command = [sys.executable, str(TOOL), "--mapping", str(self.mapping),
                   "--output-dir", str(out or self.out), *extra]
        return subprocess.run(command, capture_output=True, text=True)

    def current(self, out=None):
        root = out or self.out
        return root / json.loads((root / "current.json").read_text())["directory"]

    def tree(self, out=None):
        return {p.name: p.read_bytes() for p in sorted(self.current(out).iterdir())}

    def load(self, name, out=None):
        return json.loads((self.current(out) / name).read_text())


def identities(files):
    profile = json.loads(files["vehicle_profile.json"])
    return profile["artifact_identity"], profile["compatibility_identity"]


def normalized(files):
    """The generated bytes that must not depend on mapping spelling.

    The artifact identity (and the files embedding it) also covers the raw mapping bytes
    through the generator revision, so reordered or re-spelled mapping JSON changes it by
    design; everything else, including the compatibility identity, stays byte-identical.
    """
    profile = json.loads(files["vehicle_profile.json"])
    del profile["artifact_identity"]
    return {"profile": profile, "compatibility": profile["compatibility_identity"],
            "policies": files["validation_policies.json"],
            "catalog": files["controller_signal_catalog.json"],
            "source_report": files["source_report.json"]}


class AcceptanceCase(unittest.TestCase):
    def workspace(self, bindings=None, sources=None, **kwargs):
        sources = sources or {"demo-a.dbc": DEMO_A, "demo-b.dbc": DEMO_B}
        return Workspace(self, sources, [RPM] if bindings is None else bindings, **kwargs)

    def succeeds(self, result):
        self.assertEqual(result.returncode, 0, result.stderr)

    def assertFails(self, space, code, *fragments):
        failed = space.run()
        self.assertEqual(failed.returncode, 1, failed.stderr)
        self.assertIn(code, failed.stderr)
        for fragment in fragments:
            self.assertIn(fragment, failed.stderr)
        self.assertNotIn(str(space.root), failed.stderr)
        self.assertFalse(space.out.exists(), "a failed import must publish nothing")
        return failed.stderr


class MappingAndMergeTests(AcceptanceCase):
    """Case 1: demo-a plus demo-b compose; unbound fields are unmapped; order is irrelevant."""

    def test_duplicate_field_composes_with_both_sources_and_the_rest_is_unmapped(self):
        space = self.workspace()
        result = space.run()
        self.assertEqual(result.returncode, 0, result.stderr)
        profile = space.load("vehicle_profile.json")
        (binding,) = profile["bindings"]
        self.assertEqual(binding["key"], "vehicle.engine_rpm")
        (message,) = profile["messages"]
        (field,) = [f for f in message["fields"] if f["id"] == binding["inputs"][0]]
        self.assertEqual(sorted(field["sources"]), ["demo-a", "demo-b"])
        unmapped = [d for d in profile["diagnostics"] if d["category"] == "unmapped"]
        self.assertEqual(len(unmapped), 2)
        report = space.load("source_report.json")
        names = {entry["id"]: {a["name"] for a in entry["aliases"]}
                 for entry in report["aliases"] if entry["kind"] == "field"}
        unmapped_ids = [d["affected"] for d in report["diagnostics"]
                        if d["code"] == "unmapped_field"]
        self.assertEqual(sorted(min(names[i]) for i in unmapped_ids),
                         ["BrakePressure", "CoolantRaw"])
        originals = {a["name"] for entry in report["aliases"] if entry["kind"] == "field"
                     for a in entry["aliases"]}
        self.assertTrue({"rpm", "engine_rpm", "BrakePressure", "CoolantRaw"} <= originals)

    def test_binding_by_any_original_alias_resolves_to_the_same_field(self):
        by_a = self.workspace()
        by_b = self.workspace([dict(RPM, message="EngineExtra", field="engine_rpm")])
        self.succeeds(by_a.run())
        self.succeeds(by_b.run())
        self.assertEqual(by_a.load("vehicle_profile.json")["bindings"][0]["inputs"],
                         by_b.load("vehicle_profile.json")["bindings"][0]["inputs"])

    def test_reversed_source_order_gives_identical_bytes_and_identities(self):
        forward = self.workspace(name="forward")
        reverse = self.workspace(name="reverse")
        reverse.write(order=["demo-b.dbc", "demo-a.dbc"])
        self.assertNotEqual(forward.mapping.read_bytes(), reverse.mapping.read_bytes())
        self.succeeds(forward.run())
        self.succeeds(reverse.run())
        first, second = forward.tree(), reverse.tree()
        self.assertEqual(normalized(first), normalized(second))
        self.assertEqual(first["vehicle_profile_metadata.hpp"], second["vehicle_profile_metadata.hpp"])
        self.assertEqual(identities(first)[1], identities(second)[1])

    def test_non_selected_bus_source_is_inventoried_but_not_composed(self):
        other = HEADER.encode() + (b'BO_ 256 Engine: 8 ECU\n'
                                   b' SG_ rpm : 0|8@1+ (99,0) [0|0] "rpm" Controller\n')
        space = self.workspace(sources={"demo-a.dbc": DEMO_A, "other.dbc": other},
                               buses={"other.dbc": "chassis"})
        # A conflicting definition on another bus must neither conflict nor be composed.
        result = space.run()
        self.assertEqual(result.returncode, 0, result.stderr)
        profile = space.load("vehicle_profile.json")
        self.assertEqual([s["id"] for s in profile["sources"]], ["demo-a"])
        report = space.load("source_report.json")
        self.assertEqual({s["id"]: s["bus"] for s in report["sources"]},
                         {"demo-a": "body", "other": "chassis"})
        self.assertNotIn("other", json.dumps(report["aliases"]))

    def test_non_selected_bus_parse_errors_still_fail(self):
        broken = HEADER.encode() + b"WHAT_ 1;\n"
        space = self.workspace(sources={"demo-a.dbc": DEMO_A, "other.dbc": broken},
                               buses={"other.dbc": "chassis"})
        self.assertFails(space, "dbc_syntax_error", "other:")

    def test_classic_and_fd_fragments_of_one_key_compose_as_non_executable(self):
        classic = HEADER.encode() + (b'BO_ 700 Mix: 8 ECU\n'
                                     b' SG_ X : 0|8@1+ (1,0) [0|255] "" Controller\n')
        fd = (HEADER + FD_DEFS + 'BO_ 700 MixFd: 8 ECU\n'
              ' SG_ X : 0|8@1+ (1,0) [0|255] "" Controller\n'
              'BA_ "VFrameFormat" BO_ 700 2;\n').encode()
        sources = {"demo-a.dbc": DEMO_A, "classic.dbc": classic, "fd.dbc": fd}
        space = self.workspace(sources=sources)
        self.succeeds(space.run())
        self.assertEqual([m["identifier"] for m in space.load("vehicle_profile.json")["messages"]],
                         [256])
        unsupported = [d for d in space.load("source_report.json")["diagnostics"]
                       if d["code"] == "unsupported_message"]
        self.assertEqual(len(unsupported), 1)
        self.assertIn("can_fd", unsupported[0]["reason"])
        mixed = self.workspace([RPM, {"target": "vehicle.speed_kph", "message": "Mix",
                                      "field": "X", "unit": "rpm"}], sources=sources)
        self.assertFails(mixed, "unsupported_required_binding")


class ConflictTests(AcceptanceCase):
    UNUSED = (b'BO_ 300 Unused: 8 ECU\n'
              b' SG_ Lamp : 0|8@1+ (1,0) [0|255] "" Controller\n')

    def conflicting(self, second):
        return self.workspace(sources={"demo-a.dbc": DEMO_A + self.UNUSED,
                                       "demo-b.dbc": DEMO_B + second})

    def test_changed_duplicate_scale_fails_with_both_spans_in_an_unused_message(self):
        second = (b'BO_ 300 UnusedToo: 8 ECU\n'
                  b' SG_ Lamp : 0|8@1+ (2,0) [0|255] "" Controller\n')
        self.assertFails(self.conflicting(second), "source_conflict", "demo-a:", "demo-b:")

    def test_changed_dlc_fails_with_both_spans_in_an_unused_message(self):
        second = (b'BO_ 300 UnusedToo: 7 ECU\n'
                  b' SG_ Lamp : 0|8@1+ (1,0) [0|255] "" Controller\n')
        self.assertFails(self.conflicting(second), "source_conflict", "demo-a:", "demo-b:")

    def test_changed_scale_in_the_bound_message_fails(self):
        changed = DEMO_B.replace(b"(0.250,0.0)", b"(0.5,0.0)")
        self.assertNotEqual(changed, DEMO_B)
        space = self.workspace(sources={"demo-a.dbc": DEMO_A, "demo-b.dbc": changed})
        self.assertFails(space, "source_conflict", "demo-a:", "demo-b:")

    def test_equivalent_unused_duplicates_still_compose(self):
        space = self.conflicting(self.UNUSED.replace(b"Unused", b"UnusedToo"))
        self.succeeds(space.run())


