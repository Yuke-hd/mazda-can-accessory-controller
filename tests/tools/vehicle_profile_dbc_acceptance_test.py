@unittest.skipUnless(importlib.util.find_spec("cantools"),
                     "cantools is not installed (optional test-only differential check)")
class CantoolsDifferentialTests(unittest.TestCase):
    """Test-only oracle on the accepted subset: structure and integer mechanics, never
    binary-rounded decimals (scale/offset are compared as exact decimals)."""

    def test_structure_matches_cantools_for_the_accepted_subset(self):
        import cantools  # noqa: PLC0415  (optional test-only dependency)
        from fractions import Fraction  # noqa: PLC0415
        dbc = (HEADER + 'BO_ 256 Vec: 8 ECU\n'
               ' SG_ Intel : 4|12@1+ (1,0) [0|4095] "x" Controller\n'
               ' SG_ Moto : 23|12@0- (1,0) [-2048|2047] "y" Controller\n'
               ' SG_ Wide : 32|32@1+ (1,0) [0|4294967295] "" Controller\n').encode()
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            (root / "vec.dbc").write_bytes(dbc)
            document = {"version": 1, "profile_id": "synthetic.demo", "selected_bus": "body",
                        "sources": [{"path": "vec.dbc", "sha256": sha(dbc), "bus": "body",
                                     "license": "Apache-2.0; synthetic fixture"}],
                        "bindings": []}
            (root / "mapping.json").write_text(json.dumps(document))
            out = root / "out"
            result = subprocess.run([sys.executable, str(TOOL), "--mapping",
                                     str(root / "mapping.json"), "--output-dir", str(out)],
                                    capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stderr)
            index = json.loads((out / "current.json").read_text())
            profile = json.loads((out / index["directory"] / "vehicle_profile.json").read_text())
            database = cantools.database.load_string(dbc.decode(), database_format="dbc")
        (message,) = profile["messages"]
        oracle = database.get_message_by_frame_id(256)
        self.assertEqual(message["dlc"], oracle.length)
        ours = {f["name"]: f for f in message["fields"]}
        self.assertEqual(set(ours), {s.name for s in oracle.signals})
        for signal in oracle.signals:
            field = ours[signal.name]
            self.assertEqual(field["length"], signal.length, signal.name)
            self.assertEqual(field["start"], signal.start, signal.name)
            self.assertEqual(Fraction(field["minimum"]), Fraction(str(signal.minimum)))
            self.assertEqual(Fraction(field["maximum"]), Fraction(str(signal.maximum)))
            self.assertEqual(field["byte_order"] == "intel", signal.byte_order == "little_endian")
            self.assertEqual(field["signed"], signal.is_signed, signal.name)
            self.assertEqual(Fraction(field["scale"]), Fraction(str(signal.scale)))
            self.assertEqual(Fraction(field["offset"]), Fraction(str(signal.offset)))
            self.assertEqual(field["unit"], signal.unit or "")


