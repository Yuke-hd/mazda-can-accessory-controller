class IdentityAndTransactionTests(AcceptanceCase):
    def identities_after(self, edit):
        space = self.workspace([dict(RPM, timeout_ms=500)], name="edited")
        edit(space)
        self.succeeds(space.run())
        return identities(space.tree())

    def base(self):
        space = self.workspace([dict(RPM, timeout_ms=500)], name="base")
        self.succeeds(space.run())
        return identities(space.tree())

    def test_numeric_unit_conversion_and_freshness_changes_alter_compatibility_identity(self):
        base = self.base()

        def numeric(space):
            # Both duplicates change together so the sources still compose.
            space.sources["demo-a.dbc"] = DEMO_A.replace(b"(0.25,0)", b"(0.5,0)")
            space.sources["demo-b.dbc"] = DEMO_B.replace(b"(0.250,0.0)", b"(0.500,0.0)")
            space.write()

        def freshness(space):
            space.document["bindings"][0]["timeout_ms"] = 600
            space.write()

        def conversion(space):
            space.document["bindings"][0].update(
                unit="km/h", conversion={"scale": "2", "offset": "0"})
            space.write()

        for name, edit in (("numeric", numeric), ("freshness", freshness),
                           ("conversion", conversion)):
            with self.subTest(name):
                changed = self.identities_after(edit)
                self.assertNotEqual(changed[1], base[1])
                self.assertNotEqual(changed[0], base[0])

    def test_source_bytes_license_and_path_alter_artifact_identity_only(self):
        base = self.base()

        def source_bytes(space):
            space.sources["demo-b.dbc"] = DEMO_B + b"\n// comment only\n"
            space.write()

        def license_note(space):
            space.write(**{"demo-a.dbc": "Apache-2.0; synthetic fixture, edited"})

        def path(space):
            space.sources["renamed-a.dbc"] = space.sources.pop("demo-a.dbc")
            (space.inputs / "demo-a.dbc").unlink()
            space.write(order=["renamed-a.dbc", "demo-b.dbc"])

        for name, edit in (("source bytes", source_bytes), ("license", license_note),
                           ("path", path)):
            with self.subTest(name):
                changed = self.identities_after(edit)
                self.assertNotEqual(changed[0], base[0])
                self.assertEqual(changed[1], base[1])

    def test_explicit_identity_conversion_and_omitted_conversion_hash_the_same(self):
        omitted = self.workspace([RPM], name="omitted")
        explicit = self.workspace([dict(RPM, conversion={"scale": "1.0", "offset": "0"})],
                                  name="explicit")
        self.succeeds(omitted.run())
        self.succeeds(explicit.run())
