template <typename Predicate>
bool wait_for(Predicate predicate,
              const std::chrono::milliseconds timeout = std::chrono::milliseconds{1000}) {
  const auto deadline = std::chrono::steady_clock::now() + timeout;
  while (std::chrono::steady_clock::now() < deadline) {
    if (predicate()) {
      return true;
    }
    std::this_thread::sleep_for(std::chrono::milliseconds{1});
  }
  return predicate();
}

// The facade runs the production runtime, Mazda decoder and publication path
// over the injected seams. The destructor stops the facade before the
// consumer (its callback context) and the provider are destroyed.
struct Harness final {
  explicit Harness(const mazda::TelemetryConfig &config = test_config()) noexcept {
    mazda::internal::VehicleTelemetryAccess::emplace_host_service(telemetry, clock, source,
                                                                  lighting, config);
  }
  ~Harness() {
    if (telemetry.diagnostics().lifecycle != mazda::LifecycleState::Stopped) {
      (void)telemetry.stop();
    }
  }

  Harness(const Harness &) = delete;
  Harness &operator=(const Harness &) = delete;

  static mazda::TelemetryConfig test_config() noexcept {
    mazda::TelemetryConfig config{};
    config.callback_stop_timeout_us = 20'000;
    return config;
  }

  // Holding the clock at the frame time makes generic and typed evaluations of
  // one publication happen at the same instant.
  void inject(const std::uint32_t identifier, const vehicle_core::MonotonicTimestamp timestamp_us,
              std::initializer_list<std::uint8_t> bytes) {
    clock.set(timestamp_us);
    CHECK(source.inject(frame(identifier, timestamp_us, bytes)) == mazda::ResultCode::Ok);
  }

  FakeClock clock{};
  mazda::internal::HostAcquisitionSource source{};
  mazda::internal::NullLightingSink lighting{};
  mazda::VehicleTelemetry telemetry{};
  mazda::MazdaSignalProvider provider{telemetry};
  GenericSignalConsumer consumer{provider};
};

