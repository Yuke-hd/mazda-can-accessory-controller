// Independent typed/generic comparison. It does not use the provider's
// converter: Mazda enums compare by their raw enumerator value.

bool same_value(const SignalValue &generic, const bool typed) {
  return generic.as_boolean() == std::optional<bool>{typed};
}
bool same_value(const SignalValue &generic, const float typed) {
  return generic.as_number() == std::optional<float>{typed};
}
template <typename Enum, std::enable_if_t<std::is_enum_v<Enum>, int> = 0>
bool same_value(const SignalValue &generic, const Enum typed) {
  return generic.as_enumeration() ==
         std::optional<std::uint16_t>{static_cast<std::uint16_t>(typed)};
}

template <typename T>
bool same_reading(const SignalReading &generic, const mazda::Reading<T> &typed) {
  if (generic.value.has_value() != typed.value.has_value()) {
    return false;
  }
  if (typed.value.has_value() && !same_value(*generic.value, *typed.value)) {
    return false;
  }
  return generic.availability == typed.availability && generic.validation == typed.validation;
}

template <typename T>
bool same_notice(const SignalNotification &generic, const mazda::Notification<T> &typed) {
  return same_reading(generic.current, typed.current) && generic.initial == typed.initial &&
         generic.became_unavailable == typed.became_unavailable &&
         generic.recovered == typed.recovered && generic.coalesced == typed.coalesced;
}

bool same_generic_reading(const SignalReading &left, const SignalReading &right) {
  return left.value == right.value && left.availability == right.availability &&
         left.validation == right.validation;
}

// Typed recorder with an optional gate that holds the shared dispatcher inside
// the callback on a chosen value.
template <typename T> struct TypedRecorder final {
  mutable std::mutex mutex{};
  std::condition_variable changed{};
  mazda::Notification<T> latest{};
  std::size_t count{0};
  std::optional<T> block_on{};
  bool blocked{false};
  bool released{false};

  [[nodiscard]] std::optional<mazda::Notification<T>> snapshot() const {
    std::lock_guard<std::mutex> lock{mutex};
    if (count == 0) {
      return std::nullopt;
    }
    return latest;
  }
  [[nodiscard]] bool wait_until_blocked() {
    std::unique_lock<std::mutex> lock{mutex};
    return changed.wait_for(lock, std::chrono::milliseconds{1000}, [this] { return blocked; });
  }
  void release() {
    {
      std::lock_guard<std::mutex> lock{mutex};
      released = true;
    }
    changed.notify_all();
  }
};

template <typename T>
void record_typed(void *context, const mazda::Notification<T> &notice) noexcept {
  auto &recorder = *static_cast<TypedRecorder<T> *>(context);
  std::unique_lock<std::mutex> lock{recorder.mutex};
  recorder.latest = notice;
  ++recorder.count;
  if (recorder.block_on.has_value() && notice.current.value == recorder.block_on) {
    recorder.blocked = true;
    recorder.changed.notify_all();
    recorder.changed.wait(lock, [&recorder] { return recorder.released; });
  }
}

struct GenericRecorder final {
  mutable std::mutex mutex{};
  SignalNotification latest{};
  std::size_t count{0};

  [[nodiscard]] std::optional<SignalNotification> snapshot() const {
    std::lock_guard<std::mutex> lock{mutex};
    if (count == 0) {
      return std::nullopt;
    }
    return latest;
  }
};

void record_generic(void *context, const SignalNotification &notice) noexcept {
  auto &recorder = *static_cast<GenericRecorder *>(context);
  std::lock_guard<std::mutex> lock{recorder.mutex};
  recorder.latest = notice;
  ++recorder.count;
}

template <typename T>
bool notices_match(const std::optional<SignalNotification> &generic,
                   const std::optional<mazda::Notification<T>> &typed) {
  return generic.has_value() && typed.has_value() && same_notice(*generic, *typed);
}

template <typename T>
bool both_hold(const std::optional<SignalNotification> &generic,
               const std::optional<mazda::Notification<T>> &typed, const T expected) {
  return generic.has_value() && typed.has_value() && typed->current.value == expected &&
         generic->current.value.has_value() && same_value(*generic->current.value, expected);
}

const SignalMetadata &signal(const Harness &harness, const std::string_view key) {
  const SignalMetadata *entry = harness.provider.catalog().find(key);
  REQUIRE(entry != nullptr);
  return *entry;
}

